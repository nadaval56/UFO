def vid(orig_title_en: str, assess: str, duration: str, desc: str,
        comment: str = "", uploaded: str = "ביוני 2024", redact: bool = True) -> str:
    """Assemble a video summary_he from its unique parts.
    orig_title_en — the uploader's original (English) title, kept verbatim.
    assess — Hebrew of "...is likely derived from an infrared sensor...".
    duration — e.g. "00:00:20".  desc — Hebrew frame-by-frame description.
    uploaded — Hebrew of the classified-network upload month, e.g. "ביוני 2024".
    redact — append the standard redaction notice (a few records omit it).
    """
    s = (f"{PREAMBLE_HE} AARO מעריך כי וידאו זה, שכותרתו כפי שהגדירהּ המעלה היא "
         f"“{orig_title_en}”, {assess} משתמש העלה וידאו זה לרשת מסווגת "
         f"{uploaded}. אורך הווידאו: {duration}. תיאור הווידאו: {desc} {DISCLAIMER_HE}")
    if comment:
        s += " " + comment
    if redact:
        s += " " + REDACT_HE
    return s

